"""Build NimBLE 1.4.3 without flash storage; leave the downloaded library intact."""
from pathlib import Path


NVS_INIT = """        errRc = nvs_flash_init();

        if (errRc == ESP_ERR_NVS_NO_FREE_PAGES || errRc == ESP_ERR_NVS_NEW_VERSION_FOUND) {
            ESP_ERROR_CHECK(nvs_flash_erase());
            errRc = nvs_flash_init();
        }

        ESP_ERROR_CHECK(errRc);"""


def ram_only_device(source):
    if source.count(NVS_INIT) != 1:
        raise RuntimeError('NimBLE init changed; review the M5Apps storage adaptation')
    source = source.replace(NVS_INIT, """        // Oracle: BQ95 does not bond. M5Apps owns its apps_nvs partition;
        // no default NVS partition is required for this RAM-only BLE client.""")
    if 'nvs_flash_init(' in source or 'nvs_flash_erase(' in source:
        raise RuntimeError('Unexpected remaining NimBLE flash operation')
    return """// Generated by tools/nimble_m5apps.py from pinned NimBLE-Arduino 1.4.3.
#if !defined(MYNEWT_VAL_BLE_STORE_CONFIG_PERSIST) || MYNEWT_VAL_BLE_STORE_CONFIG_PERSIST != 0
#error Oracle BLE requires RAM-only storage
#endif
""" + source


def configure(env):
    def replace_device(env, node):
        original = Path(node.srcnode().get_abspath())
        properties = original.parent.parent / 'library.properties'
        if 'version=1.4.3' not in properties.read_text().splitlines():
            raise RuntimeError('Review M5Apps adaptation before upgrading NimBLE')
        patched = ram_only_device(original.read_text())
        generated = Path(env.subst('$BUILD_DIR')) / 'oracle-generated/NimBLEDevice.cpp'
        generated.parent.mkdir(parents=True, exist_ok=True)
        if not generated.exists() or generated.read_text() != patched:
            generated.write_text(patched)
        return env.File(str(generated.resolve()))

    env.AddBuildMiddleware(replace_device, '*/NimBLE-Arduino/src/NimBLEDevice.cpp')


if 'Import' in globals():
    Import('env')
    configure(env)
