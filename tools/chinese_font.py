"""Redistributable /efont/ 12px glyphs for firmware and thermal receipts."""
import functools
import hashlib
import json
import re
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

@functools.lru_cache(maxsize=1)
def glyphs():
    result = {}
    source = (ROOT/'assets/fonts/efont-b12.bdf').read_text()
    for block in source.split('STARTCHAR ')[1:]:
        cp = int(re.search(r'^ENCODING (\d+)', block, re.M)[1])
        width, height, left, bottom = map(int, re.search(r'^BBX (.*)', block, re.M)[1].split())
        advance = int(re.search(r'^DWIDTH (\d+)', block, re.M)[1])
        bitmap = block.split('BITMAP', 1)[1].split('ENDCHAR', 1)[0].split()
        rows = [0]*12
        for y, value in enumerate(bitmap):
            top = 10-bottom-height+y
            if not 0 <= top < 12: continue
            bits = int(value, 16)
            for x in range(width):
                if 0 <= left+x < 12 and bits & (1 << (len(value)*4-1-x)):
                    rows[top] |= 1 << (11-left-x)
        result[cp] = (12 if wide(cp) else advance, rows)
    return result

def wide(cp):
    return 0x3000 <= cp <= 0x303f or 0x3400 <= cp <= 0x9fff or 0xff01 <= cp <= 0xff60

def validate_book(data):
    if len(data)<12: raise ValueError('Truncated Chinese font')
    magic,count,crc=struct.unpack('<4sII',data[:12])
    if magic!=b'OCF1' or not 0<count<=65536 or len(data)!=12+count*26 or zlib.crc32(data[12:])!=crc:
        raise ValueError('Invalid Chinese font header, length or checksum')
    previous=-1
    for offset in range(12,len(data),26):
        cp,*rows=struct.unpack('<13H',data[offset:offset+26])
        if cp<=previous or not wide(cp) or any(r>4095 for r in rows):
            raise ValueError('Invalid Chinese glyph record')
        previous=cp

class BitmapFont:
    def __init__(self, scale=2): self.scale = scale
    def getlength(self, text):
        return sum(glyphs()[ord(c)][0]*self.scale for c in text)

def draw_text(draw, xy, text, font, anchor='lt', fill=0):
    if not isinstance(font, BitmapFont):
        return draw.text(xy, text, font=font, anchor=anchor, fill=fill)
    x, y = xy
    if anchor == 'mt': x -= font.getlength(text)//2
    for c in text:
        advance, rows = glyphs()[ord(c)]
        for row, bits in enumerate(rows):
            for col in range(12):
                if bits & (1 << (11-col)):
                    px, py = x+col*font.scale, y+row*font.scale
                    draw.rectangle((px, py, px+font.scale-1, py+font.scale-1), fill=fill)
        x += advance*font.scale

def build():
    all_glyphs = glyphs()
    deck = json.loads((ROOT/'content/deck.zh.json').read_text())
    texts = json.dumps(deck, ensure_ascii=False)
    for directory in ('firmware/src', 'firmware/include/oracle'):
        for path in (ROOT/directory).rglob('*'):
            if path.suffix in ('.cpp', '.h') and 'chinese_glyphs' not in path.name:
                texts += path.read_text()
    required = sorted({ord(c) for c in texts if wide(ord(c))})
    missing = [chr(cp) for cp in required if cp not in all_glyphs]
    if missing: raise ValueError('Missing Chinese glyphs: '+''.join(missing))
    records = b''.join(struct.pack('<13H', cp, *rows) for cp, (_, rows) in sorted(all_glyphs.items()) if wide(cp))
    target = ROOT/'sdcard/ORACLE/fonts/chinese12.bin'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(struct.pack('<4sII', b'OCF1', len(records)//26, zlib.crc32(records))+records)
    validate_book(target.read_bytes())
    lines = ['// Generated by tools/chinese_font.py; /efont/ license in third_party/Efont-LICENSE.',
             'struct ChineseGlyph { std::uint16_t code; std::uint16_t rows[12]; };',
             'static constexpr ChineseGlyph kChineseGlyphs[] = {']
    for cp in required:
        lines.append('{'+str(cp)+',{'+','.join(str(r) for r in all_glyphs[cp][1])+'}},')
    lines.append('};')
    header=ROOT/'firmware/include/oracle/chinese_glyphs.h'
    generated='\n'.join(lines)+'\n'
    if not header.exists() or header.read_text()!=generated: header.write_text(generated)
    manifest = {'source':'https://raw.githubusercontent.com/olikraus/u8g2/master/tools/font/bdf/b12.bdf',
                'source_sha256':hashlib.sha256((ROOT/'assets/fonts/efont-b12.bdf').read_bytes()).hexdigest(),
                'license':'third_party/Efont-LICENSE', 'size':12,
                'embedded_glyphs':len(required), 'sd_glyphs':len(records)//26}
    (ROOT/'assets/fonts/manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(f'Chinese font: {len(required)} embedded glyphs, {len(records)//26} SD glyphs')

if __name__ == '__main__': build()
