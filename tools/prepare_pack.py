#!/usr/bin/env python3
"""Validate one source deck; export bounded per-card SD JSON, C++ fallback and receipt HTML."""
import argparse
import html
import json
from pathlib import Path
import re
import wave

ROOT = Path(__file__).resolve().parents[1]

def validate(deck, media_root=None, require_media=False):
    if deck.get('schema') != 1 or not isinstance(deck.get('cards'), list) or not 1 <= len(deck['cards']) <= 256:
        raise ValueError('Expected schema 1 with 1..256 cards')
    ids = set()
    for card in deck['cards']:
        ident = card.get('id', '')
        if not re.fullmatch(r'[a-z0-9_]{1,24}', ident) or ident in ids:
            raise ValueError(f'Invalid/duplicate ID: {ident}')
        ids.add(ident)
        for key, limit, nonempty in [('title',48,True), ('text',1400,True), ('topic',48,False)]:
            value = card.get(key, '')
            if not isinstance(value,str) or len(value.encode()) > limit or (nonempty and not value):
                raise ValueError(f'{ident}: invalid {key}')
            if any(not (32 <= ord(c) <= 126 or '\u0410' <= c <= '\u044f' or c in 'Ёё\n') for c in value):
                raise ValueError(f'{ident}: unsupported glyph in {key}')
        if len(card['title']) > 23 or type(card.get('motif')) is not int or not 0 <= card['motif'] < 4:
            raise ValueError(f'{ident}: title/motif out of range')
        if card.get('topic') not in ('life','it','beer','tea'):
            raise ValueError(f'{ident}: unsupported topic')
        for field, ext in [('audio','.wav'),('image','.jpg')]:
            value = card.get(field, '')
            if require_media and not value:
                raise ValueError(f'{ident}: {field} required for release')
            if not value:
                continue
            if not re.fullmatch(r'/ORACLE/[A-Za-z0-9_/.-]{1,88}',value) or '..' in value or not value.endswith(ext):
                raise ValueError(f'{ident}: unsafe {field} path')
            path = (media_root or ROOT/'sdcard') / value.lstrip('/')
            if not path.is_file():
                raise ValueError(f'{ident}: missing media {path}')
            if field == 'audio':
                with wave.open(str(path),'rb') as wav:
                    if wav.getnchannels()!=1 or wav.getsampwidth()!=2 or not 8000<=wav.getframerate()<=48000 or not wav.getnframes() or wav.getcomptype()!='NONE':
                        raise ValueError(f'{ident}: expected nonempty mono PCM16 WAV, 8..48 kHz')
            else:
                from PIL import Image
                with Image.open(path) as im:
                    if im.format!='JPEG' or im.size!=(92,92):
                        raise ValueError(f'{ident}: image must be 92x92 JPEG')
                    im.verify()
    return deck['cards']

def build(deck_path=ROOT/'content/deck.json', strict=False, ready_only=False):
    all_cards = validate(json.loads(deck_path.read_text()))
    cards = [c for c in all_cards if c.get('audio') and c.get('image')] if ready_only else all_cards
    validate({'schema':1,'cards':cards}, require_media=strict or ready_only)
    sd = ROOT/'sdcard/ORACLE'
    (sd/'cards').mkdir(parents=True,exist_ok=True)
    (sd/'index.json').write_text(json.dumps({'schema':1,'ids':[c['id'] for c in cards],
        'themes':[{'life':0,'it':0,'beer':1,'tea':2}[c['topic']] for c in cards]},indent=2)+'\n')
    rows = []
    for c in cards:
        card = {'schema':1, **c, 'audio':c.get('audio',''), 'image':c.get('image','')}
        (sd/'cards'/f"{c['id']}.json").write_text(json.dumps(card,ensure_ascii=False,indent=2)+'\n')
    # Keep a small offline fallback in flash; the complete voiced deck is on SD.
    fallback_counts = {'humor_it':0, 'beer':0, 'tea':0}
    for c in all_cards:
        theme = c['topic'] if c['topic'] in ('beer','tea') else 'humor_it'
        if fallback_counts[theme] >= 6: continue
        fallback_counts[theme] += 1
        fields = ', '.join(json.dumps(c[k],ensure_ascii=False) for k in ['id','title','text','topic'])
        rows.append('    {'+fields+', '+str(c['motif'])+'},')
    (ROOT/'firmware/include/oracle/builtin_deck.h').write_text(
        '// Generated by tools/prepare_pack.py: six fallback cards per offline theme.\n#pragma once\nnamespace oracle {\n'
        'struct BuiltinRecord { const char *id, *title, *text, *topic; unsigned motif; };\n'
        'static const BuiltinRecord kBuiltinDeck[] = {\n'+'\n'.join(rows)+'\n};\n}\n')
    receipts = []
    for c in cards:
        e = lambda key: html.escape(c[key])
        receipts.append(f'<article><small>БЮРО НЕТОЧНЫХ ПРОГНОЗОВ</small><div class="sigil">✧ ◉ ✧</div><h2>{e("title")}</h2><p>{e("text")}</p><footer>ПРОГНОЗ #{e("id").upper()}<br>Звёзды старались. Гарантий нет.</footer></article>')
    (ROOT/'docs/receipts.html').write_text('''<!doctype html><html lang="ru"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Оракул · макеты чеков</title><style>
body{margin:0;background:#201b2c;color:#1a1720;font-family:monospace;padding:32px}header{max-width:850px;color:#eee4d5;margin:0 auto 30px}h1{font:36px Georgia}header p{line-height:1.7;color:#c5b9d2}.grid{display:flex;flex-wrap:wrap;gap:24px;justify-content:center;align-items:flex-start}article{box-sizing:border-box;background:#fffdf4;padding:28px 26px;width:320px;box-shadow:0 7px 20px #0003;border-bottom:6px dotted #201b2c}small{display:block;text-align:center;font-size:11px;letter-spacing:1px}.sigil{text-align:center;font-size:46px;margin:22px 0}h2{text-align:center;font-size:20px}article p{font-size:17px;line-height:1.65}footer{font-size:11px;text-align:center;border-top:1px dashed;padding-top:18px;line-height:1.8}@media print{body{background:white;padding:0}header{display:none}article{box-shadow:none;break-inside:avoid;border:1px dashed #999}}
</style><header><h1>Бюро неточных прогнозов</h1><p>Демонстрационная колода готовых предсказаний. Макеты для обсуждения; реальная ширина и растеризация будут настроены после проверки принтера. Это не отправка на печать.</p></header><main class="grid">'''+''.join(receipts)+'</main></html>')
    print(f'Validated {len(cards)} cards; generated SD pack, fallback header and receipt preview. Media required: {strict}')

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--require-media',action='store_true')
    parser.add_argument('--ready-only',action='store_true',help='Export only cards with both generated voice and artwork')
    args=parser.parse_args()
    build(strict=args.require_media,ready_only=args.ready_only)
