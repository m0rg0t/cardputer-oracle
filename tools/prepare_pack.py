#!/usr/bin/env python3
"""Validate a language deck and build a self-contained SD directory."""
import argparse
import json
from pathlib import Path
import re
import shutil
import wave
from languages import ROOT, LANGUAGES, deck_path as language_deck, pack_root
def validate(deck, media_root=None, require_media=False):
    if deck.get('schema') != 1 or not isinstance(deck.get('cards'), list) or not 1 <= len(deck['cards']) <= 256:
        raise ValueError('Expected schema 1 with 1..256 cards')
    ids = set()
    for card in deck['cards']:
        ident = card.get('id', '')
        if not re.fullmatch(r'[a-z0-9_]{1,24}', ident) or ident in ids:
            raise ValueError(f'Invalid/duplicate ID: {ident}')
        ids.add(ident)
        for key, limit, nonempty in [('title',48,True), ('text',1400,True), ('topic',48,False)]:
            value = card.get(key, '')
            if not isinstance(value,str) or len(value.encode()) > limit or (nonempty and not value):
                raise ValueError(f'{ident}: invalid {key}')
            if any(not (32 <= ord(c) <= 126 or '\u0410' <= c <= '\u044f' or c in 'Ёё\n' or
                        c in '“”‘’—–…' or '\u3000'<=c<='\u303f' or '\u3400'<=c<='\u9fff' or '\uff01'<=c<='\uff60') for c in value):
                raise ValueError(f'{ident}: unsupported glyph in {key}')
            if any(ord(c)>=0x3000 for c in value):
                from chinese_font import glyphs, wide
                if any(wide(ord(c)) and ord(c) not in glyphs() for c in value):
                    raise ValueError(f'{ident}: missing Chinese font glyph in {key}')
        if len(card['title']) > 23 or type(card.get('motif')) is not int or not 0 <= card['motif'] < 4:
            raise ValueError(f'{ident}: title/motif out of range')
        if card.get('topic') not in ('life','it','beer','tea'):
            raise ValueError(f'{ident}: unsupported topic')
        for field, ext in [('audio','.wav'),('image','.jpg')]:
            value = card.get(field, '')
            if require_media and not value:
                raise ValueError(f'{ident}: {field} required for release')
            if not value:
                continue
            if not re.fullmatch(r'/ORACLE/[A-Za-z0-9_/.-]{1,88}',value) or '..' in value or not value.endswith(ext):
                raise ValueError(f'{ident}: unsafe {field} path')
            path = (media_root or ROOT/'sdcard') / value.lstrip('/')
            if not path.is_file():
                raise ValueError(f'{ident}: missing media {path}')
            if field == 'audio':
                with wave.open(str(path),'rb') as wav:
                    if wav.getnchannels()!=1 or wav.getsampwidth()!=2 or not 8000<=wav.getframerate()<=48000 or not wav.getnframes() or wav.getcomptype()!='NONE':
                        raise ValueError(f'{ident}: expected nonempty mono PCM16 WAV, 8..48 kHz')
            else:
                from PIL import Image
                with Image.open(path) as im:
                    if im.format!='JPEG' or im.size!=(92,92):
                        raise ValueError(f'{ident}: image must be 92x92 JPEG')
                    im.verify()
    return deck['cards']

def generate_fallback(language):
    deck=json.loads(language_deck(language).read_text())
    cards=validate({'schema':1,'cards':[{**c,'audio':'','image':''} for c in deck['cards']]})
    counts={'humor_it':0,'beer':0,'tea':0}; rows=[]
    for c in cards:
        theme=c['topic'] if c['topic'] in ('beer','tea') else 'humor_it'
        if counts[theme]>=6: continue
        counts[theme]+=1
        fields=', '.join(json.dumps(c[k],ensure_ascii=False) for k in ('id','title','text','topic'))
        rows.append('    {'+fields+', '+str(c['motif'])+'},')
    path=ROOT/f'firmware/include/oracle/builtin_deck_{language}.h'
    text=('// Generated by tools/prepare_pack.py; six fallback cards per theme.\n#pragma once\n'
          'namespace oracle {\nstruct BuiltinRecord { const char *id, *title, *text, *topic; unsigned motif; };\n'
          'static const BuiltinRecord kBuiltinDeck[] = {\n'+'\n'.join(rows)+'\n};\n}\n')
    if not path.exists() or path.read_text()!=text: path.write_text(text)

def build(deck_path=None, strict=False, ready_only=False, language='en'):
    if language not in LANGUAGES: raise ValueError('Unsupported language')
    source=deck_path or language_deck(language)
    deck=json.loads(source.read_text())
    if deck.get('language')!=language: raise ValueError('Deck language mismatch')
    cards=validate(deck,require_media=strict)
    if ready_only: cards=[c for c in cards if c.get('audio') and c.get('image')]
    validate({'schema':1,'cards':cards},require_media=strict or ready_only)
    output=pack_root(language); sd=output/'ORACLE'
    (sd/'cards').mkdir(parents=True,exist_ok=True)
    index={'schema':1,'language':language,'ids':[c['id'] for c in cards],
           'themes':[{'life':0,'it':0,'beer':1,'tea':2}[c['topic']] for c in cards]}
    (sd/'index.json').write_text(json.dumps(index,indent=2)+'\n')
    for c in cards:
        if c.get('audio'):
            audio=ROOT/'sdcard'/c['audio'].lstrip('/')
            meta=json.loads(audio.with_suffix('.json').read_text())
            if meta.get('text')!=c['text'] or meta.get('language','ru')!=language:
                raise ValueError('Stale/wrong-language narration: '+c['id'])
        (sd/'cards'/f'{c["id"]}.json').write_text(json.dumps({'schema':1,**c},ensure_ascii=False,indent=2)+'\n')
        for field in ('audio','image'):
            if c.get(field):
                target=output/c[field].lstrip('/'); target.parent.mkdir(parents=True,exist_ok=True)
                shutil.copyfile(ROOT/'sdcard'/c[field].lstrip('/'),target)
    for rel in ('config.example.json','tls/roots.pem')+(('fonts/chinese12.bin',) if language=='zh' else ()):
        target=sd/rel; target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(ROOT/'sdcard/ORACLE'/rel,target)
    generate_fallback(language)
    print(f'{language}: {len(cards)} cards exported to {output}')
    return output

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--language',choices=LANGUAGES,default='en')
    parser.add_argument('--require-media',action='store_true')
    parser.add_argument('--ready-only',action='store_true')
    parser.add_argument('--fallback-only',action='store_true',help='Generate both firmware fallback headers without media')
    args=parser.parse_args()
    if args.fallback_only:
        for language in LANGUAGES: generate_fallback(language)
    else: build(strict=args.require_media,ready_only=args.ready_only,language=args.language)
